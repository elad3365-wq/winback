#!/usr/bin/env python3
"""Build supabase/production/pilot_upgrade.sql from the repo migrations.

One transaction that brings the PRODUCTION database (any state from 0001-0003
upward) to the schema the pilot release expects: 0004-0010, multi-business,
Gmail (0011), autopilot (0012), Gmail push (0013), advisor hardening, and
security hardening (0014). The WinBack-Test-only guards are removed and
replaced by one guard that refuses to run ON WinBack-Test. Re-runnable.
"""
import pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
M = ROOT / "supabase" / "migrations"
PARTS = [
    M / "0004_beta_signups.sql",
    M / "0005_onboarding.sql",
    M / "0006_ai_messages.sql",
    M / "0007_ai_message_approvals.sql",
    M / "0008_lead_status_values.sql",
    M / "0009_autopilot_foundation.sql",
    M / "0010_lead_notes_activity.sql",
    M / "0011_multi_business.sql",
    M / "0011_business_gmail.sql",
    M / "0012_ai_autopilot.sql",
    M / "0013_gmail_push.sql",
    ROOT / "supabase" / "preview" / "winback_test_hardening_2026_11_17.sql",
    M / "0014_security_hardening.sql",
]
MARKER_GUARD = re.compile(
    r"\n\s*if to_regnamespace\('winback_test_marker'\) is null then\n\s*raise exception [^\n]*\n\s*end if;",
)
HEADER = """-- WinBack PRODUCTION pilot upgrade (generated by scripts/build-production-upgrade.py).
-- DO NOT EDIT BY HAND. Run once in the PRODUCTION project's SQL Editor
-- (yysmbjnspenslykzmlel), only after elad approves. One transaction: if any
-- statement fails, nothing is changed. Safe to re-run. Deletes no rows and
-- changes no existing row's data.
begin;

do $$
begin
  if to_regnamespace('winback_test_marker') is not null then
    raise exception 'STOPPED: this is WinBack-Test, not production. Nothing was changed.';
  end if;
  if to_regclass('public.businesses') is null or to_regclass('public.leads') is null
     or to_regproc('public.is_business_member') is null then
    raise exception 'STOPPED: migrations 0001-0003 are missing. Nothing was changed.';
  end if;
end
$$;
"""
FOOTER = """
-- Self-check: every object the pilot release needs must exist now.
do $$
declare missing text[] := '{}';
begin
  if to_regclass('public.beta_signups') is null then missing := missing || 'beta_signups'; end if;
  if to_regclass('public.business_ai_settings') is null then missing := missing || 'business_ai_settings'; end if;
  if to_regclass('public.ai_messages') is null then missing := missing || 'ai_messages'; end if;
  if to_regclass('public.lead_activity') is null then missing := missing || 'lead_activity'; end if;
  if to_regclass('public.business_knowledge') is null then missing := missing || 'business_knowledge'; end if;
  if to_regclass('public.ai_usage') is null then missing := missing || 'ai_usage'; end if;
  if to_regproc('public.create_business') is null then missing := missing || 'create_business'; end if;
  if to_regproc('public.ai_reserve_call') is null then missing := missing || 'ai_reserve_call'; end if;
  if to_regproc('public.consume_rate_limit') is null then missing := missing || 'consume_rate_limit'; end if;
  if array_length(missing, 1) > 0 then
    raise exception 'UPGRADE INCOMPLETE, rolled back. Missing: %', array_to_string(missing, ', ');
  end if;
  raise notice 'WINBACK PILOT UPGRADE OK';
end
$$;

commit;
"""

def body(path: pathlib.Path) -> str:
    text = path.read_text()
    text = MARKER_GUARD.sub("", text)
    # Inner begin/commit would end our transaction early.
    text = re.sub(r"(?mi)^\s*(begin|commit);\s*$", "", text)
    return f"\n-- ==== {path.name} ====\n{text}\n"

out = HEADER + "".join(body(p) for p in PARTS) + FOOTER
assert "winback_test_marker') is null" not in out
(ROOT / "supabase" / "production" / "pilot_upgrade.sql").write_text(out)
print("wrote", len(out), "bytes")
